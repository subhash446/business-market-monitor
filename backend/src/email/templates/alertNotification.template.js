function buildAlertNotification({
  materialName,
  conditionType,
  thresholdType = 'ABSOLUTE',
  thresholdPrice,
  triggeredPrice,
  triggeredChangePercent = null,
  currency = 'INR',
  unitLabel = null,
  triggeredAt,
}) {
  const currSym = currency === 'USD' ? '$' : (currency === 'INR' ? '₹' : `${currency} `);
  const unitSuffix = unitLabel ? ` / ${unitLabel}` : '';

  let conditionText = '';
  let subject = '';

  if (thresholdType === 'PERCENTAGE') {
    const isAbove = conditionType === 'PRICE_ABOVE';
    conditionText = isAbove ? `Price increase ≥ ${thresholdPrice}%` : `Price drop ≥ ${thresholdPrice}%`;
    const changeFormatted = triggeredChangePercent !== null && triggeredChangePercent !== undefined
      ? `${Number(triggeredChangePercent) >= 0 ? '+' : ''}${Number(triggeredChangePercent).toFixed(2)}%`
      : 'N/A';
    subject = `Price Alert: ${materialName} ${conditionText} (Triggered: ${changeFormatted})`;
  } else {
    const condition = conditionType === 'PRICE_ABOVE' ? 'Price Above' : 'Price Below';
    conditionText = `${condition} ${currSym}${Number(thresholdPrice).toFixed(2)}${unitSuffix}`;
    subject = `Price Alert: ${materialName} ${condition} ${currSym}${Number(thresholdPrice).toFixed(2)}`;
  }

  const changeRow = thresholdType === 'PERCENTAGE' && triggeredChangePercent !== null && triggeredChangePercent !== undefined
    ? `<tr>
         <td style="padding: 10px; border: 1px solid #ddd;"><strong>Observed Change</strong></td>
         <td style="padding: 10px; border: 1px solid #ddd; font-weight: bold; color: ${Number(triggeredChangePercent) >= 0 ? '#b91c1c' : '#15803d'};">
           ${Number(triggeredChangePercent) >= 0 ? '+' : ''}${Number(triggeredChangePercent).toFixed(2)}%
         </td>
       </tr>`
    : '';

  const html = `
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 24px; color: #1f2937;">
      <h2 style="margin-bottom: 20px; color: #111827;">🚨 Price Alert Triggered</h2>

      <p>Your configured market alert rule for <strong>${materialName}</strong> has been triggered.</p>

      <table style="border-collapse: collapse; width: 100%; margin-top: 20px;">
        <tr>
          <td style="padding: 10px; border: 1px solid #ddd; width: 40%;"><strong>Material</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${materialName}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Alert Rule</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${conditionText}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Threshold</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">
            ${thresholdType === 'PERCENTAGE' ? `${Number(thresholdPrice).toFixed(2)}%` : `${currSym}${Number(thresholdPrice).toFixed(2)}${unitSuffix}`}
          </td>
        </tr>

        ${changeRow}

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Triggered Price</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd; font-family: monospace; font-size: 1.1em;">
            ${currSym}${Number(triggeredPrice).toFixed(2)}${unitSuffix}
          </td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Triggered At</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${new Date(triggeredAt).toISOString()}</td>
        </tr>
      </table>

      <p style="margin-top: 24px; font-size: 12px; color: #6b7280;">
        This automated alert was generated by Business Market Monitor. You can manage your alert rules and notification settings in your dashboard.
      </p>
    </div>
  `;

  return { subject, html };
}

module.exports = { buildAlertNotification };
