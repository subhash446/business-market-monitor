function buildAlertNotification({
  materialName,
  conditionType,
  thresholdPrice,
  triggeredPrice,
  triggeredAt,
}) {
  const condition =
    conditionType === 'PRICE_ABOVE'
      ? 'Price Above'
      : 'Price Below';

  const subject = `Price Alert: ${materialName} ${condition} ₹${Number(thresholdPrice).toFixed(2)}`;

  const html = `
    <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 24px;">
      <h2 style="margin-bottom: 20px;">🚨 Price Alert</h2>

      <p>Your configured price alert has been triggered.</p>

      <table style="border-collapse: collapse; width: 100%; margin-top: 20px;">
        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Material</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${materialName}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Condition</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${condition}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Threshold Price</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">₹${Number(thresholdPrice).toFixed(2)}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Triggered Price</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">₹${Number(triggeredPrice).toFixed(2)}</td>
        </tr>

        <tr>
          <td style="padding: 10px; border: 1px solid #ddd;"><strong>Triggered At</strong></td>
          <td style="padding: 10px; border: 1px solid #ddd;">${new Date(triggeredAt).toLocaleString('en-IN')}</td>
        </tr>
      </table>

      <p style="margin-top: 24px; color: #555;">
        This alert was generated by Business Market Monitor.
      </p>
    </div>
  `;

  return {
    subject,
    html,
  };
}

module.exports = {
  buildAlertNotification,
};